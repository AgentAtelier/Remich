//! Asset request specification for LLM‑driven asset pipeline contract.

use crate::error::{ValidationErrors, error_buffer};
use crate::push_validation_error;
use crate::{ArchetypeTag, FailureClass, SemanticArtifact, TerrainType, Versioned};
use serde::{Deserialize, Serialize};
use std::fmt;

// Byte limits for text fields
const MAX_STYLE_CONTEXT_BYTES: usize = 200;
const MAX_PROMPT_CORE_BYTES: usize = 600;

// ---------------------------------------------------------------------------
// AssetRequestSpec – LLM → deterministic asset pipeline contract
// ---------------------------------------------------------------------------

/// Typed request authored by LLM-facing graphics tooling.
///
/// This is semantic input only. Deterministic pipeline stages enrich this
/// request with a style suffix and composed full prompt downstream.
///
/// - `prompt_core`: The base prompt describing the asset geometry and structure.
/// - `style_context`: Art direction context that influences the visual style.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AssetRequestSpec {
    /// The family/category of asset being requested.
    pub asset_family: AssetRequestFamily,
    /// The archetype tag identifying this specific asset type.
    pub archetype_tag: ArchetypeTag,
    /// The biome context for styling the asset, if applicable.
    pub biome_context: Option<TerrainType>,
    /// Art direction context that influences the visual style.
    pub style_context: String,
    /// The base prompt describing the asset geometry and structure.
    pub prompt_core: String,
    /// Quality level hint for generation.
    pub quality_hint: Option<AssetRequestQualityHint>,
    /// Source hint indicating how the asset was created.
    pub source_hint: Option<AssetRequestSourceHint>,
}

// ---------------------------------------------------------------------------
// Asset enums
// ---------------------------------------------------------------------------

/// The family/category of asset being requested.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum AssetRequestFamily {
    /// Major landmark asset.
    HeroLandmark,
    /// Modular building components.
    ArchitectureKit,
    /// Plant life and foliage.
    Vegetation,
    /// Decorative objects.
    Prop,
    /// Terrain surface details.
    TerrainDetail,
    /// Surface decals/textures.
    Decal,
}

/// Quality level hint for asset generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum AssetRequestQualityHint {
    /// Low quality, for testing.
    Draft,
    /// Full quality, for production.
    Production,
    /// Unknown quality level.
    #[serde(other)]
    Unknown,
}

/// Source hint indicating how the asset was created.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum AssetRequestSourceHint {
    /// Manually created by an artist.
    HandAuthored,
    /// Generated by AI.
    AiGenerated,
    /// Acquired from a third-party source.
    Purchased,
    /// Unknown source.
    #[serde(other)]
    Unknown,
}

