/// Builder for [`AssetRequestSpec`] with fluent API.
#[derive(Debug, Default)]
pub struct AssetRequestSpecBuilder {
    /// The asset family to set.
    asset_family: Option<AssetRequestFamily>,
    /// The archetype tag to set.
    archetype_tag: Option<ArchetypeTag>,
    /// The biome context to set.
    biome_context: Option<Option<TerrainType>>,
    /// The style context to set.
    style_context: Option<String>,
    /// The prompt core to set.
    prompt_core: Option<String>,
    /// The quality hint to set.
    quality_hint: Option<Option<AssetRequestQualityHint>>,
    /// The source hint to set.
    source_hint: Option<Option<AssetRequestSourceHint>>,
}

/// Error type for `AssetRequestSpecBuilder::try_build`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BuildError {
    /// A required field was not set before calling `try_build()`.
    MissingField(&'static str),
}

impl BuildError {
    /// Create a new error for a missing required field.
    pub fn missing(field: &'static str) -> Self {
        Self::MissingField(field)
    }
}

impl std::fmt::Display for BuildError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            BuildError::MissingField(field) => write!(f, "missing required field: {}", field),
        }
    }
}

impl std::error::Error for BuildError {}

impl AssetRequestSpecBuilder {
    /// Create a new empty builder.
    pub fn new() -> Self {
        Self::default()
    }

    /// Set the asset family.
    pub fn asset_family(mut self, value: AssetRequestFamily) -> Self {
        self.asset_family = Some(value);
        self
    }

    /// Set the archetype tag.
    pub fn archetype_tag(mut self, value: ArchetypeTag) -> Self {
        self.archetype_tag = Some(value);
        self
    }

    /// Set the biome context. Use `None` for no biome context.
    pub fn biome_context(mut self, value: Option<TerrainType>) -> Self {
        self.biome_context = Some(value);
        self
    }

    /// Set the style context from any string-like value.
    pub fn style_context(mut self, value: impl Into<String>) -> Self {
        self.style_context = Some(value.into());
        self
    }

    /// Set the prompt core from any string-like value.
    pub fn prompt_core(mut self, value: impl Into<String>) -> Self {
        self.prompt_core = Some(value.into());
        self
    }

    /// Set the quality hint. Use `None` for no quality hint.
    pub fn quality_hint(mut self, value: Option<AssetRequestQualityHint>) -> Self {
        self.quality_hint = Some(value);
        self
    }

    /// Set the source hint. Use `None` for no source hint.
    pub fn source_hint(mut self, value: Option<AssetRequestSourceHint>) -> Self {
        self.source_hint = Some(value);
        self
    }

    /// Build the [`AssetRequestSpec`], returning an error if any required field is not set.
    pub fn try_build(self) -> Result<AssetRequestSpec, BuildError> {
        Ok(AssetRequestSpec {
            asset_family: self.asset_family.ok_or(BuildError::missing("asset_family"))?,
            archetype_tag: self.archetype_tag.ok_or(BuildError::missing("archetype_tag"))?,
            biome_context: self.biome_context.unwrap_or(None),
            style_context: self.style_context.ok_or(BuildError::missing("style_context"))?,
            prompt_core: self.prompt_core.ok_or(BuildError::missing("prompt_core"))?,
            quality_hint: self.quality_hint.unwrap_or(None),
            source_hint: self.source_hint.unwrap_or(None),
        })
    }

    /// Build the [`AssetRequestSpec`].
    ///
    /// # Panics
    /// Panics if any required field is not set.
    ///
    /// # Deprecated
    /// Use `try_build` instead to handle missing fields gracefully.
    #[deprecated = "Use try_build() instead"]
    #[allow(clippy::expect_used)]
    pub fn build(self) -> AssetRequestSpec {
        self.try_build().expect("AssetRequestSpecBuilder: missing required fields")
    }
}

impl AssetRequestSpec {
    /// Create a new builder for [`AssetRequestSpec`].
    pub fn builder() -> AssetRequestSpecBuilder {
        AssetRequestSpecBuilder::new()
    }
}

impl SemanticArtifact for AssetRequestSpec {
    fn validate(&self) -> ValidationErrors {
        let mut errors = error_buffer();

        let style = self.style_context.trim();
        let prompt = self.prompt_core.trim();

        // Validate style_context bounds (E012 empty, E016 overflow)
        if style.is_empty() {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E012",
                self.artifact_type_name(),
                "style_context",
                style.to_owned(),
                "style_context cannot be empty"
            );
        }
        if style.len() > MAX_STYLE_CONTEXT_BYTES {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E016",
                self.artifact_type_name(),
                "style_context",
                format!("{} bytes", style.len()),
                format!("style_context exceeds {} bytes", MAX_STYLE_CONTEXT_BYTES)
            );
        }

        // Validate prompt_core bounds (E013 empty, E014 overflow)
        if prompt.is_empty() {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E013",
                self.artifact_type_name(),
                "prompt_core",
                prompt.to_owned(),
                "prompt_core cannot be empty"
            );
        }
        if prompt.len() > MAX_PROMPT_CORE_BYTES {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E014",
                self.artifact_type_name(),
                "prompt_core",
                format!("{} bytes", prompt.len()),
                format!("prompt_core exceeds {} bytes", MAX_PROMPT_CORE_BYTES)
            );
        }

        // Check for control-character injection (E018, E019)
        let has_control = |s: &str| s.chars().any(|c| c.is_control() && c != '\n' && c != '\t');
        if has_control(prompt) {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E018",
                self.artifact_type_name(),
                "prompt_core",
                prompt.to_owned(),
                "prompt_core contains prohibited control characters"
            );
        }
        if has_control(style) {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E019",
                self.artifact_type_name(),
                "style_context",
                style.to_owned(),
                "style_context contains prohibited control characters"
            );
        }

        // Check for unknown variants (E017)
        if let Some(ref quality) = self.quality_hint
            && matches!(quality, AssetRequestQualityHint::Unknown)
        {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E017",
                self.artifact_type_name(),
                "quality_hint",
                format!("{}", quality),
                "unknown variant encountered; update the schema",
                warning
            );
        }
        if let Some(ref source) = self.source_hint
            && matches!(source, AssetRequestSourceHint::Unknown)
        {
            push_validation_error!(
                errors,
                FailureClass::Semantic,
                "E017",
                self.artifact_type_name(),
                "source_hint",
                format!("{}", source),
                "unknown variant encountered; update the schema",
                warning
            );
        }

        errors
    }
}

