#[cfg(test)]
mod tests {
    use super::*;

    fn valid_spec() -> AssetRequestSpec {
        AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("highlands_watchtower").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "northern weathered stone".to_string(),
            prompt_core: "broken watchtower with collapsed upper ring and mossy foundation"
                .to_string(),
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        }
    }

    #[test]
    fn valid_spec_passes() {
        let spec = valid_spec();
        assert_eq!(spec.version(), 1);
        assert!(spec.validate().is_empty());
    }

    #[test]
    fn empty_prompt_core_fails() {
        let mut spec = valid_spec();
        spec.prompt_core = "   ".to_string();
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("prompt_core cannot be empty"));
    }

    #[test]
    fn empty_style_context_fails() {
        let mut spec = valid_spec();
        spec.style_context = String::new();
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("style_context cannot be empty"));
    }

    #[test]
    fn prompt_core_at_boundary() {
        // Exactly 600 bytes should pass ("x" is 1 byte, so 600 "x" chars = 600 bytes)
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "test".to_string(),
            prompt_core: "x".repeat(600),
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        assert!(spec.validate().is_empty());

        // 601 bytes should fail
        let mut spec = valid_spec();
        spec.prompt_core = "x".repeat(601);
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("prompt_core exceeds 600 bytes"));
    }

    #[test]
    fn style_context_at_boundary() {
        // Exactly 200 bytes should pass ("x" is 1 byte, so 200 "x" chars = 200 bytes)
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "x".repeat(200),
            prompt_core: "test prompt".to_string(),
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        assert!(spec.validate().is_empty());

        // 201 bytes should fail
        let mut spec = valid_spec();
        spec.style_context = "x".repeat(201);
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("style_context exceeds 200 bytes"));
    }

    #[test]
    fn missing_tag_is_valid() {
        let tag = ArchetypeTag::missing();
        assert_eq!(tag.as_str(), "missing");
        // missing() tag should be creatable and valid
        assert!(ArchetypeTag::new("missing").is_ok());
    }

    #[test]
    fn missing_tag_in_spec_passes() {
        // A spec with the "missing" archetype tag should be valid
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::Prop,
            archetype_tag: ArchetypeTag::new("missing").expect("valid missing tag"),
            biome_context: None,
            style_context: "simple".to_string(),
            prompt_core: "a simple prop".to_string(),
            quality_hint: None,
            source_hint: None,
        };
        assert!(spec.validate().is_empty());
    }

    #[test]
    fn roundtrip_serialization() {
        let spec = valid_spec();
        let json = serde_json::to_string(&spec).expect("serialize spec");
        let decoded: AssetRequestSpec = serde_json::from_str(&json).expect("deserialize spec");
        assert_eq!(decoded, spec);
    }

    #[test]
    fn unknown_quality_hint_is_warning() {
        // Unknown quality hint should produce a warning, not an error
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "test style".to_string(),
            prompt_core: "test prompt".to_string(),
            quality_hint: Some(AssetRequestQualityHint::Unknown),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        let errors = spec.validate();
        assert!(!errors.is_empty());
        assert!(errors[0].is_warning());
        assert!(errors[0].to_string().contains("E017"));
    }

    #[test]
    fn control_char_rejected() {
        // Control characters (except \n and \t) should be rejected in prompt_core (E018)
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "test style".to_string(),
            prompt_core: "test\x00prompt".to_string(), // null byte
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("E018") || msg.contains("control characters"));

        // Also test style_context with control char (E019)
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: "test\x01style".to_string(), // SOH character
            prompt_core: "test prompt".to_string(),
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        let errors = spec.validate();
        assert!(!errors.is_empty());
        let msg = errors[0].to_string();
        assert!(msg.contains("E019") || msg.contains("control characters"));
    }

    #[test]
    fn multi_byte_boundary() {
        // Test with multi-byte UTF-8 characters (e.g., emoji are 4 bytes each)
        // 200 bytes limit for style_context: 50 emoji = 200 bytes exactly
        let emoji = "🎨"; // 4 bytes
        let spec = AssetRequestSpec {
            asset_family: AssetRequestFamily::HeroLandmark,
            archetype_tag: ArchetypeTag::new("test_tag").expect("valid tag"),
            biome_context: Some(TerrainType::Highlands),
            style_context: emoji.repeat(50), // 50 * 4 = 200 bytes
            prompt_core: "test".to_string(),
            quality_hint: Some(AssetRequestQualityHint::Production),
            source_hint: Some(AssetRequestSourceHint::AiGenerated),
        };
        assert!(spec.validate().is_empty());

        // 51 emoji = 204 bytes exceeds 200 limit
        let mut spec = spec;
        spec.style_context = emoji.repeat(51);
        let errors = spec.validate();
        assert!(!errors.is_empty());
        assert!(errors[0].to_string().contains("200 bytes"));
    }

    #[test]
    fn builder_roundtrip() {
        let spec = AssetRequestSpec::builder()
            .asset_family(AssetRequestFamily::HeroLandmark)
            .archetype_tag(ArchetypeTag::new("test_builder").expect("valid tag"))
            .biome_context(Some(TerrainType::Highlands))
            .style_context("builder style")
            .prompt_core("builder prompt")
            .quality_hint(Some(AssetRequestQualityHint::Production))
            .source_hint(Some(AssetRequestSourceHint::HandAuthored))
            .try_build()
            .expect("builder should have all required fields");

        assert_eq!(spec.asset_family, AssetRequestFamily::HeroLandmark);
        assert_eq!(spec.archetype_tag.as_str(), "test_builder");
        assert_eq!(spec.biome_context, Some(TerrainType::Highlands));
        assert_eq!(spec.style_context, "builder style");
        assert_eq!(spec.prompt_core, "builder prompt");
        assert_eq!(spec.quality_hint, Some(AssetRequestQualityHint::Production));
        assert_eq!(spec.source_hint, Some(AssetRequestSourceHint::HandAuthored));
        assert!(spec.validate().is_empty());
    }
}
